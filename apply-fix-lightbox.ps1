#  Regenere 2 fichiers :
#    src/components/MediaGallery.tsx       (lightbox via createPortal(document.body))
#    src/components/MediaGallery.test.tsx  (nouveau : test du portail, focus, fermeture)
#  Lancer depuis la RACINE du repo :
#    powershell -ExecutionPolicy Bypass -File .\apply-fix-lightbox.ps1
