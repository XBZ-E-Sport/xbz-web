param([switch]$Force)
$ErrorActionPreference = 'Stop'

if (-not (Test-Path '.\package.json') -or -not (Test-Path '.\src\app')) {
  throw "Lance ce script depuis la racine du repo xbz-web."
}
$branch = (git rev-parse --abbrev-ref HEAD).Trim()
if ($branch -ne 'refonte-da') {
  Write-Host ("  attention : branche courante = " + $branch + " (attendu : refonte-da)") -ForegroundColor Yellow
}

# Garde-fou : ne pas ecraser des modifs locales non commitees sur ces fichiers.
$targets = @(
  'src/components/MediaGallery.tsx',
  'src/components/MediaGallery.test.tsx'
)
if (-not $Force) {
  $dirty = @(git status --porcelain) | ForEach-Object { $_.Substring(3).Trim('"') }
  $clash = @($targets | Where-Object { $dirty -contains $_ })
  if ($clash.Count -gt 0) {
    Write-Host 'Modifs locales non commitees sur :' -ForegroundColor Red
    $clash | ForEach-Object { Write-Host ('  ' + $_) -ForegroundColor Red }
    throw 'Commit/stash ces fichiers d''abord, ou relance avec -Force.'
  }
}

function Write-FileFromB64([string]$Path, [string]$B64) {
  $full = [System.IO.Path]::GetFullPath((Join-Path (Get-Location) $Path))
  $dir  = [System.IO.Path]::GetDirectoryName($full)
  if (-not [System.IO.Directory]::Exists($dir)) { [System.IO.Directory]::CreateDirectory($dir) | Out-Null }
  [System.IO.File]::WriteAllBytes($full, [Convert]::FromBase64String($B64))
  Write-Host ('  ecrit : ' + $Path) -ForegroundColor Green
}

